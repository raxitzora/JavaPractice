package collections;

import java.util.HashSet;
import java.util.LinkedHashSet;
import java.util.Set;

public class SetsDemo {
    public static void main(String[] args) {

        //HashSet
        Set<Integer> num = new HashSet<>();
        num.add(10);
        num.add(20);
        num.add(30);
        num.add(40);

        
        //LinkedHashSet

        Set<Integer> set = new LinkedHashSet<>();

set.add(30);
set.add(10);
set.add(20);

    }

    
}
